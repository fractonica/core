static uint64_t count_call_value;
#define COUNT_CALL(buf, size) frc_format_count(count_call_value, (buf), (size))

static void test_count(void)
{
    char text[64], want[64], plain[32];
    size_t i;

    TEST_SECTION("frc_format_count: every row of the oracle");
    for (i = 0; i < ORACLE_PURE_COUNT_COUNT; i++) {
        const oracle_pure_count_t *row = &oracle_pure_count[i];
        int n = frc_format_count(row->n, text, sizeof text);
        CHECK_EQ_I64(n, (int)strlen(row->text));
        CHECK_STR(text, row->text);
        CHECK_NOTE("n = %" PRIu64, row->n);
        /* the rule restated here: printf's digits, grouped */
        snprintf(plain, sizeof plain, "%" PRIu64, row->n);
        group_decimal(plain, want);
        CHECK_STR(text, want);
        strip_groups(text, want);
        CHECK_STR(want, plain);
    }
    CHECK(ORACLE_PURE_LONGEST_COUNT == 38);

    TEST_SECTION("frc_format_count: every power of ten and its neighbours");
    {
        uint64_t power = 1;
        int k;
        for (k = 0; k <= 19; k++) {
            int d;
            for (d = -1; d <= 1; d++) {
                uint64_t n = power + (uint64_t)d; /* 10^0 - 1 is 0 */
                int length = frc_format_count(n, text, sizeof text);
                int digits = snprintf(plain, sizeof plain, "%" PRIu64, n);
                /* one separator of three bytes for every full group after the first */
                CHECK_EQ_I64(length, digits + 3 * ((digits - 1) / 3));
                group_decimal(plain, want);
                CHECK_STR(text, want);
            }
            if (k < 19) {
                power *= 10;
            }
        }
    }

    TEST_SECTION("frc_format_count: the buffer");
    {
        static const uint64_t values[] = {0, 7, 999, 1000, 58500, UINT64_C(142033641750000), UINT64_MAX};
        for (i = 0; i < sizeof values / sizeof values[0]; i++) {
            count_call_value = values[i];
            CHECK(frc_format_count(values[i], text, sizeof text) > 0);
            strcpy(want, text);
            CHECK_EVERY_SIZE(COUNT_CALL, want);
        }
    }
    /* by hand: exact fit, one short (the group space goes whole or not at all), size 1, size 0 */
    memset(text, '#', sizeof text);
    CHECK_EQ_I64(frc_format_count(1000, text, 8), 7);
    CHECK_STR(text, "1" NNBSP "000");
    memset(text, '#', sizeof text);
    CHECK_EQ_I64(frc_format_count(1000, text, 7), FRC_ERR_BUFFER);
    CHECK_STR(text, "1" NNBSP "00");
    CHECK_EQ_I64(frc_format_count(1000, text, 5), FRC_ERR_BUFFER);
    CHECK_STR(text, "1" NNBSP);
    CHECK_EQ_I64(frc_format_count(1000, text, 4), FRC_ERR_BUFFER);
    CHECK_STR(text, "1"); /* two bytes of the three-byte space would fit: never half a code point */
    CHECK_EQ_I64(frc_format_count(1000, text, 2), FRC_ERR_BUFFER);
    CHECK_STR(text, "1");
    CHECK_EQ_I64(frc_format_count(1000, text, 1), FRC_ERR_BUFFER);
    CHECK_STR(text, "");
    CHECK_EQ_I64(frc_format_count(1000, text, 0), FRC_ERR_BUFFER);
    CHECK_EQ_I64(frc_format_count(1000, NULL, 8), FRC_ERR_BUFFER);
}

