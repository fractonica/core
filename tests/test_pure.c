/*
 * test_pure.c - tests of src/frc_pure.c, the pure wordings of fractonica.h:
 *
 *   frc_format_count            a whole number in digit groups
 *   frc_format_level_in_unit    a cycle of a level counted in a unit
 *   frc_format_level_rate       a rung in cycles per Blink
 *   frc_format_light_span       a length as a span of light
 *
 * Expected values come from four places, in this order of authority:
 *   1. Typed in here by hand: the texts fractonica.h and the design rulings
 *      print ("1η light", "58 500ν", "2 772 pB", "1 per 58 500 Blinks").
 *   2. tests/vectors/oracle_pure.h, generated by tools/oracle/generate-pure.mjs
 *      with exact BigInt rationals and no call into this library: every count
 *      around a grouping boundary, every (level, unit) pair, every level at
 *      five precisions, every level in every medium with and without the
 *      word, speeds chosen to stand on every tie and carry, and every
 *      twentieth of a Blink from 1 to 10 (each tenth, each tie between two,
 *      each whole number of quarter Blinks).
 *   3. The rest of the library: a rate down to the Blink is the text of
 *      frc_format_per_blink, a light span of light in vacuum down to the
 *      Blink is the text of frc_format_span for frc_span_of_level, a rate
 *      times P(12) is the prefix frc_format_prefix prints.
 *   4. Rules restated here on decimal strings: grouping, and the rounding of
 *      a rate to 2..9 digits (the oracle carries four of those precisions).
 *      No rate of the ladder rounds up into the next decade, so the rounding
 *      itself (frc_i_limbs_round) is also held directly on numbers that do.
 * Then the contract of every text writer, for every buffer size.
 *
 * Nothing here uses floating point: the program is the same under FRC_NO_FLOAT.
 */
