#define MIDDOT "\xC2\xB7"
#define MINUS_SIGN "\xE2\x88\x92"

/* "12 345" with U+202F, from a plain decimal string. */
static void group_digits(const char *digits, char *out)
{
    size_t n = strlen(digits), i;
    for (i = 0; i < n; i++) {
        *out++ = digits[i];
        if (i + 1 < n && (n - i - 1) % 3 == 0) {
            memcpy(out, NNBSP, 3);
            out += 3;
        }
    }
    *out = '\0';
}

/* The every-size contract for texts longer than CHECK_EVERY_SIZE's buffer. */
static int (*long_call)(char *, size_t);
static void check_every_size_long(const char *full)
{
    size_t length = strlen(full), size;
    static char buf[1024];
    for (size = 0; size <= length + 2; size++) {
        int n;
        memset(buf, '#', sizeof buf);
        n = long_call(buf, size);
        CHECK(buf[size] == '#');
        if (size > length) {
            CHECK_EQ_I64(n, (int)length);
            CHECK_STR(buf, full);
        } else {
            CHECK_EQ_I64(n, FRC_ERR_BUFFER);
            if (size > 0) {
                size_t kept = bounded_length(buf, size);
                CHECK(kept < size);
                CHECK(strncmp(buf, full, kept) == 0);
                CHECK(((unsigned char)full[kept] & 0xC0u) != 0x80u);
            }
        }
    }
    CHECK_EQ_I64(long_call(NULL, 64), FRC_ERR_BUFFER);
}

/* decimal string * small factor, in place */
static void decimal_times(char *digits, unsigned factor)
{
    char out[80];
    int i, n = (int)strlen(digits), o = 79;
    unsigned carry = 0;
    out[o] = '\0';
    for (i = n - 1; i >= 0; i--) {
        unsigned v = (unsigned)(digits[i] - '0') * factor + carry;
        out[--o] = (char)('0' + v % 10);
        carry = v / 10;
    }
    while (carry) {
        out[--o] = (char)('0' + carry % 10);
        carry /= 10;
    }
    strcpy(digits, out + o);
}

static uint8_t kind_value;
#define KIND_CALL(buf, size) frc_format_level_kind((frc_level_kind_t)kind_value, (buf), (size))
static int64_t signed_value;
#define SIGNED_CALL(buf, size) frc_format_count_signed(signed_value, (buf), (size))
static frc_cycle_t place_cycle;
#define PLACE_CALL(buf, size) frc_format_cycle_place(&place_cycle, (buf), (size))
#define PLACE_NULL_CALL(buf, size) frc_format_cycle_place(NULL, (buf), (size))
static uint8_t tree_level;
#define CHILDREN_CALL(buf, size) frc_format_level_children(tree_level, (buf), (size))
#define IN_PARENT_CALL(buf, size) frc_format_level_in_parent(tree_level, (buf), (size))
#define UNIT_PARENT_CALL(buf, size) frc_format_unit_in_parent((frc_unit_t)tree_level, (buf), (size))
#define FACTORS_CALL(buf, size) frc_format_prefix_factors(tree_level, (buf), (size))
static int factors_call(char *buf, size_t size)
{
    return frc_format_prefix_factors(tree_level, buf, size);
}
#define LIGHT_WORD_CALL(buf, size) frc_format_light_word((buf), (size))

static void test_rulings_and_places(void)
{
    static const char *const kinds[4] = {"major", "unit", "between", "sub-Blink"};
    char text[600], want[600], name[16], digits[80];
    int i;
    size_t longest;

    TEST_SECTION("frc_format_level_kind: the words of ruling 4, and every level's");
    for (kind_value = 0; kind_value < 4; kind_value++) {
        CHECK_EVERY_SIZE(KIND_CALL, kinds[kind_value]);
    }
    for (i = 0; i < FRC_LEVEL_COUNT; i++) {
        const char *want_kind = (i <= 3) ? "major" : (i <= 12 && i % 2 == 0) ? "unit" : (i <= 12) ? "between" : "sub-Blink";
        CHECK(frc_format_level_kind(frc_level_kind((uint8_t)i), text, sizeof text) > 0);
        CHECK_STR(text, want_kind);
    }
    kind_value = 4;
    CHECK_REFUSED(KIND_CALL, FRC_ERR_ARG);
    kind_value = 255;
    CHECK_REFUSED(KIND_CALL, FRC_ERR_ARG);

    TEST_SECTION("frc_format_count_signed: against snprintf, INT64_MIN included");
    for (i = 0; i < 200000; i++) {
        int64_t n = (int64_t)(rng() >> (rng() % 64));
        char plain[32];
        if (i % 2 && n != INT64_MIN) {
            n = -n;
        }
        if (i == 0) n = INT64_MIN;
        if (i == 1) n = INT64_MAX;
        if (i == 2) n = 0;
        if (i == 3) n = -1;
        snprintf(plain, sizeof plain, "%" PRIu64, n < 0 ? (uint64_t)0 - (uint64_t)n : (uint64_t)n);
        group_digits(plain, digits);
        snprintf(want, sizeof want, "%s%s", n < 0 ? MINUS_SIGN : "", digits);
        CHECK_EQ_I64(frc_format_count_signed(n, text, sizeof text), (int)strlen(want));
        CHECK_STR(text, want);
        CHECK_NOTE("%" PRId64, n);
        if (n >= 0) {
            char unsigned_text[64];
            frc_format_count((uint64_t)n, unsigned_text, sizeof unsigned_text);
            CHECK_STR(text, unsigned_text); /* the same digits as frc_format_count */
        }
    }
    signed_value = INT64_MIN;
    CHECK_EVERY_SIZE(SIGNED_CALL, MINUS_SIGN "9" NNBSP "223" NNBSP "372" NNBSP "036" NNBSP "854" NNBSP "775" NNBSP "808");
    CHECK_EQ_U64(strlen(MINUS_SIGN "9" NNBSP "223" NNBSP "372" NNBSP "036" NNBSP "854" NNBSP "775" NNBSP "808"), 40);
    signed_value = -3;
    CHECK_EVERY_SIZE(SIGNED_CALL, MINUS_SIGN "3");

    TEST_SECTION("frc_format_cycle_place: every level at random instants");
    for (i = 0; i < 20000; i++) {
        frc_time_t t = frc_catalogue_first(&FRC_SAROS_141)
                       + (frc_time_t)(rng() % (uint64_t)(frc_catalogue_last(&FRC_SAROS_141) - frc_catalogue_first(&FRC_SAROS_141)));
        uint8_t level = (uint8_t)(rng() % (FRC_CLOCK_MAX_LEVEL + 1));
        frc_cycle_t cycle;
        CHECK(frc_cycle_at(&FRC_SAROS_141, t, level, &cycle) == FRC_OK);
        snprintf(want, sizeof want, "%u of %u", (unsigned)cycle.local + 1, (unsigned)cycle.siblings);
        CHECK(frc_format_cycle_place(&cycle, text, sizeof text) > 0);
        CHECK_STR(text, want);
        CHECK_NOTE("level %u", level);
    }
    place_cycle.local = 7;
    place_cycle.siblings = 9;
    CHECK_EVERY_SIZE(PLACE_CALL, "8 of 9");
    place_cycle.local = 65534;
    place_cycle.siblings = 65535;
    CHECK_EVERY_SIZE(PLACE_CALL, "65" NNBSP "535 of 65" NNBSP "535");
    CHECK_EQ_U64(strlen("65" NNBSP "535 of 65" NNBSP "535"), 20);
    place_cycle.local = 9;
    CHECK(frc_format_cycle_place(&place_cycle, text, sizeof text) > 0); /* 10 of 65 535 */
    place_cycle.local = 9;
    place_cycle.siblings = 9;
    CHECK_REFUSED(PLACE_CALL, FRC_ERR_ARG);
    place_cycle.local = 0;
    place_cycle.siblings = 0;
    CHECK_REFUSED(PLACE_CALL, FRC_ERR_ARG);
    CHECK_REFUSED(PLACE_NULL_CALL, FRC_ERR_ARG);

    TEST_SECTION("frc_format_level_children / _level_in_parent: every level");
    longest = 0;
    for (i = 0; i < FRC_LEVEL_COUNT; i++) {
        tree_level = (uint8_t)i;
        if (i + 1 < FRC_LEVEL_COUNT) {
            frc_format_level_name((uint8_t)(i + 1), name, sizeof name);
            snprintf(want, sizeof want, "%u %s", (unsigned)frc_factor((uint8_t)i), name);
            CHECK_EVERY_SIZE(CHILDREN_CALL, want);
            longest = strlen(want) > longest ? strlen(want) : longest;
        } else {
            CHECK_REFUSED(CHILDREN_CALL, FRC_ERR_ARG);
        }
    }
    CHECK_EQ_U64(longest, 6);
    longest = 0;
    for (i = 0; i < FRC_LEVEL_COUNT; i++) {
        tree_level = (uint8_t)i;
        if (i > 0) {
            frc_format_level_name((uint8_t)(i - 1), name, sizeof name);
            snprintf(want, sizeof want, "%u in %s", (unsigned)frc_siblings((uint8_t)i), name);
            CHECK_EVERY_SIZE(IN_PARENT_CALL, want);
            longest = strlen(want) > longest ? strlen(want) : longest;
        } else {
            CHECK_REFUSED(IN_PARENT_CALL, FRC_ERR_ARG);
        }
    }
    CHECK_EQ_U64(longest, 9);
    for (i = FRC_LEVEL_COUNT; i < 256; i++) {
        tree_level = (uint8_t)i;
        CHECK_REFUSED(CHILDREN_CALL, FRC_ERR_ARG);
        CHECK_REFUSED(IN_PARENT_CALL, FRC_ERR_ARG);
        CHECK_REFUSED(FACTORS_CALL, FRC_ERR_ARG);
    }

    TEST_SECTION("frc_format_unit_in_parent: every unit");
    {
        static const char *const in_parent[FRC_UNIT_COUNT] = {
            NULL, "5 in \xCE\xB1", "13 in \xCE\xB2", "5 in \xCE\xB3", "5 in \xCE\xB4",
            "77 in \xCE\xB5", "36 in " ETA, "65 in " IOTA, "25 in " LAMBDA};
        for (i = 0; i < 256; i++) {
            tree_level = (uint8_t)i;
            if (i >= 1 && i < FRC_UNIT_COUNT) {
                CHECK_EVERY_SIZE(UNIT_PARENT_CALL, in_parent[i]);
                /* the count is the parts of the next coarser unit */
                snprintf(want, sizeof want, "%u in ", (unsigned)frc_unit_parts((frc_unit_t)(i - 1)));
                CHECK(strncmp(in_parent[i], want, strlen(want)) == 0);
            } else {
                CHECK_REFUSED(UNIT_PARENT_CALL, FRC_ERR_ARG);
            }
        }
    }

    TEST_SECTION("frc_format_prefix_factors: every level, against frc_format_prefix and a product");
    longest = 0;
    for (i = 0; i < FRC_LEVEL_COUNT; i++) {
        char product[80] = "1", exact[80];
        int l;
        size_t o;
        tree_level = (uint8_t)i;
        CHECK(frc_format_prefix((uint8_t)i, exact, sizeof exact) > 0);
        for (l = 0; l < i; l++) {
            decimal_times(product, frc_factor((uint8_t)l));
        }
        CHECK_STR(product, exact); /* the factors multiply to the prefix */
        group_digits(exact, want);
        o = strlen(want);
        for (l = 0; l < i; l++) {
            o += (size_t)snprintf(want + o, sizeof want - o, "%s%u", l == 0 ? " = " : " " MIDDOT " ",
                                  (unsigned)frc_factor((uint8_t)l));
        }
        long_call = factors_call;
        check_every_size_long(want);
        longest = o > longest ? o : longest;
    }
    CHECK_EQ_U64(longest, 428); /* fractonica.h: level 62, 428 bytes + NUL */
    tree_level = 6;
    CHECK(frc_format_prefix_factors(6, text, sizeof text) > 0);
    CHECK_STR(text, "125" NNBSP "125 = 5 " MIDDOT " 13 " MIDDOT " 5 " MIDDOT " 5 " MIDDOT " 7 " MIDDOT " 11");
    CHECK(frc_format_prefix_factors(0, text, sizeof text) == 1);
    CHECK_STR(text, "1");
    CHECK(frc_format_prefix_factors(1, text, sizeof text) > 0);
    CHECK_STR(text, "5 = 5");

    TEST_SECTION("frc_format_light_word: the one word of ruling 2");
    CHECK_EVERY_SIZE(LIGHT_WORD_CALL, "light");
    for (i = 0; i < FRC_LEVEL_COUNT; i++) {
        uint8_t medium;
        for (medium = 0; medium < FRC_MEDIUM_COUNT; medium++) {
            char bare[64], word[16];
            CHECK(frc_format_light_span((uint8_t)i, frc_medium_speed((frc_medium_t)medium), 0, bare, sizeof bare) > 0);
            CHECK(frc_format_light_span((uint8_t)i, frc_medium_speed((frc_medium_t)medium), 1, text, sizeof text) > 0);
            CHECK(frc_format_light_word(word, sizeof word) == 5);
            snprintf(want, sizeof want, "%s %s", bare, word);
            CHECK_STR(text, want);
        }
    }
}

