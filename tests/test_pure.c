static uint8_t in_unit_level;
static frc_unit_t in_unit_unit;
#define IN_UNIT_CALL(buf, size) frc_format_level_in_unit(in_unit_level, in_unit_unit, (buf), (size))

static void test_level_in_unit(void)
{
    char text[64], want[64];
    size_t i;
    int level, unit;
    int valid = 0, refused = 0;

    TEST_SECTION("frc_format_level_in_unit: the oracle's units are the library's");
    CHECK(ORACLE_PURE_UNIT_COUNT == FRC_UNIT_COUNT);
    for (unit = 0; unit < FRC_UNIT_COUNT; unit++) {
        CHECK_EQ_U64(frc_unit_level((frc_unit_t)unit), oracle_pure_units[unit].level);
        CHECK(frc_format_unit_symbol((frc_unit_t)unit, text, sizeof text) > 0);
        CHECK_STR(text, oracle_pure_units[unit].symbol);
        CHECK(frc_format_unit_name((frc_unit_t)unit, 0, text, sizeof text) > 0);
        CHECK_STR(text, oracle_pure_units[unit].name);
    }

    TEST_SECTION("frc_format_level_in_unit: every (level, unit) pair");
    CHECK(ORACLE_PURE_IN_UNIT_COUNT == ORACLE_PURE_IN_UNIT_LEVELS * FRC_UNIT_COUNT);
    CHECK(ORACLE_PURE_IN_UNIT_LEVELS == 13);
    for (i = 0; i < ORACLE_PURE_IN_UNIT_COUNT; i++) {
        const oracle_pure_in_unit_t *row = &oracle_pure_in_unit[i];
        int n;
        CHECK(row->level == i / FRC_UNIT_COUNT && row->unit == i % FRC_UNIT_COUNT);
        in_unit_level = row->level;
        in_unit_unit = (frc_unit_t)row->unit;
        memset(text, '#', sizeof text);
        n = frc_format_level_in_unit(row->level, (frc_unit_t)row->unit, text, sizeof text);
        if (row->status == ORACLE_PURE_OK) {
            valid++;
            CHECK_EQ_I64(n, (int)strlen(row->text));
            CHECK_STR(text, row->text);
            CHECK_NOTE("level %u in unit %u", row->level, row->unit);
            /* the count is P(level of unit) / P(level), and the text is that count and the symbol */
            CHECK(frc_unit_level((frc_unit_t)row->unit) >= row->level);
            CHECK_EQ_U64(frc_prefix(frc_unit_level((frc_unit_t)row->unit)), row->count * frc_prefix(row->level));
            CHECK(frc_format_count(row->count, want, sizeof want) > 0);
            strcat(want, oracle_pure_units[row->unit].symbol);
            CHECK_STR(text, want);
            CHECK(n <= ORACLE_PURE_LONGEST_IN_UNIT);
            CHECK_EVERY_SIZE(IN_UNIT_CALL, row->text);
        } else {
            refused++;
            CHECK(row->status == ORACLE_PURE_ERR_ARG);
            /* refused exactly when the unit is coarser than the level */
            CHECK(frc_unit_level((frc_unit_t)row->unit) < row->level);
            CHECK_REFUSED(IN_UNIT_CALL, FRC_ERR_ARG);
        }
    }
    CHECK_EQ_I64(valid, 55);
    CHECK_EQ_I64(refused, 62);
    CHECK(ORACLE_PURE_LONGEST_IN_UNIT == 21);
    /* a unit counted in itself is one of it; a level in the next finer unit is frc_unit_parts */
    for (unit = 0; unit < FRC_UNIT_COUNT; unit++) {
        uint8_t own = frc_unit_level((frc_unit_t)unit);
        CHECK(frc_format_level_in_unit(own, (frc_unit_t)unit, text, sizeof text) > 0);
        snprintf(want, sizeof want, "1%s", oracle_pure_units[unit].symbol);
        CHECK_STR(text, want);
        if (unit + 1 < FRC_UNIT_COUNT) {
            CHECK(frc_format_level_in_unit(own, (frc_unit_t)(unit + 1), text, sizeof text) > 0);
            snprintf(want, sizeof want, "%u%s", frc_unit_parts((frc_unit_t)unit), oracle_pure_units[unit + 1].symbol);
            CHECK_STR(text, want);
        }
    }

    TEST_SECTION("frc_format_level_in_unit: refused arguments");
    /* a level below the Blink, with every unit; every level, with something that is not a unit */
    for (level = 13; level <= 255; level++) {
        for (unit = 0; unit < FRC_UNIT_COUNT; unit++) {
            in_unit_level = (uint8_t)level;
            in_unit_unit = (frc_unit_t)unit;
            CHECK_REFUSED(IN_UNIT_CALL, FRC_ERR_ARG);
        }
    }
    for (level = 0; level <= 255; level++) {
        static const int not_units[] = {FRC_UNIT_COUNT, 10, 127, 255, -1};
        for (i = 0; i < sizeof not_units / sizeof not_units[0]; i++) {
            in_unit_level = (uint8_t)level;
            in_unit_unit = (frc_unit_t)not_units[i];
            CHECK_REFUSED(IN_UNIT_CALL, FRC_ERR_ARG);
        }
    }
}

/* ------------------------------------------------------------------------- */
/* frc_format_level_rate                                                      */
/* ------------------------------------------------------------------------- */

static uint8_t rate_level, rate_digits;
#define RATE_CALL(buf, size) frc_format_level_rate(rate_level, rate_digits, (buf), (size))

static void test_level_rate(void)
{
    char text[128], want[128], plain[128], prefix[64], product[96];
    int level;
    unsigned digits;
    size_t i;
    int in_full = 0, powers = 0, carried = 0;

    TEST_SECTION("frc_format_level_rate: every level at the oracle's precisions");
    CHECK(ORACLE_PURE_RATE_COUNT == FRC_LEVEL_COUNT);
    for (level = 0; level < FRC_LEVEL_COUNT; level++) {
        const oracle_pure_rate_t *row = &oracle_pure_rate[level];
        CHECK(row->level == level);
        for (i = 0; i < ORACLE_PURE_RATE_DIGITS; i++) {
            int n = frc_format_level_rate((uint8_t)level, oracle_pure_rate_digits[i], text, sizeof text);
            CHECK_EQ_I64(n, (int)strlen(row->text[i]));
            CHECK_STR(text, row->text[i]);
            CHECK_NOTE("level %d, digits %u", level, oracle_pure_rate_digits[i]);
            CHECK(n <= ORACLE_PURE_LONGEST_RATE);
        }
    }
    CHECK(ORACLE_PURE_LONGEST_RATE == 84);

    TEST_SECTION("frc_format_level_rate: down to the Blink it is frc_format_per_blink, byte for byte");
    for (level = 0; level <= 12; level++) {
        uint64_t num = 0, den = 0;
        int n_want;
        CHECK(frc_level_per_blink((uint8_t)level, &num, &den) == FRC_OK);
        n_want = frc_format_per_blink(num, den, want, sizeof want);
        CHECK(n_want > 0);
        for (digits = 0; digits <= 9; digits++) {
            if (digits == 1) {
                continue;
            }
            memset(text, '#', sizeof text);
            CHECK_EQ_I64(frc_format_level_rate((uint8_t)level, (uint8_t)digits, text, sizeof text), n_want);
            CHECK(memcmp(text, want, (size_t)n_want + 1) == 0);
            CHECK(text[n_want + 1] == '#');
        }
        /* and the oracle's exact ratio is the library's */
        snprintf(plain, sizeof plain, "%" PRIu64, num);
        CHECK_STR(plain, oracle_pure_rate[level].num);
        snprintf(plain, sizeof plain, "%" PRIu64, den);
        CHECK_STR(plain, oracle_pure_rate[level].den);
    }

    TEST_SECTION("frc_format_level_rate: below the Blink, every digit of the exact rate");
    for (level = 13; level < FRC_LEVEL_COUNT; level++) {
        const char *exact = oracle_pure_rate[level].num;
        uint64_t num = 0, den = 0;
        CHECK_STR(oracle_pure_rate[level].den, "1");
        /* in full: the digits of N, grouped; N * P(12) is the prefix of the level */
        CHECK(frc_format_level_rate((uint8_t)level, 0, text, sizeof text) > 0);
        strip_groups(text, plain);
        snprintf(want, sizeof want, "%s pB", exact);
        CHECK_STR(plain, want);
        multiply_decimal(exact, frc_prefix(12), product, sizeof product);
        CHECK(frc_format_prefix((uint8_t)level, prefix, sizeof prefix) > 0);
        CHECK_STR(product, prefix);
        /* where frc_level_per_blink still fits, it is the same number */
        if (level <= 35) {
            CHECK(frc_level_per_blink((uint8_t)level, &num, &den) == FRC_OK && den == 1);
            snprintf(plain, sizeof plain, "%" PRIu64, num);
            CHECK_STR(plain, exact);
        } else {
            CHECK(frc_level_per_blink((uint8_t)level, &num, &den) == FRC_ERR_OVERFLOW);
        }
        /* every precision 0, 2..9 against the rule restated on the decimal string */
        for (digits = 0; digits <= 9; digits++) {
            int n;
            if (digits == 1) {
                continue;
            }
            expected_rate(exact, digits, want);
            n = frc_format_level_rate((uint8_t)level, (uint8_t)digits, text, sizeof text);
            CHECK_EQ_I64(n, (int)strlen(want));
            CHECK_STR(text, want);
            CHECK_NOTE("level %d, digits %u", level, digits);
            if (strstr(text, TIMES) != NULL) {
                powers++;
                /* "d." then digits - 1 more digits, then the sign */
                CHECK(text[1] == '.' && text[digits + 1] == ' ' && text[0] != '0');
            } else {
                in_full++;
            }
        }
    }
    /* levels 13..19 are below a million (7 levels x 9 precisions), and digits 0 is always in full */
    CHECK_EQ_I64(in_full, 7 * 9 + (LAST_LEVEL - 19));
    CHECK_EQ_I64(powers, (LAST_LEVEL - 19) * 8);

    TEST_SECTION("frc_format_level_rate: a mantissa that rounds up to 10");
    /* The helper above, on strings no rung has. */
    expected_rate("9996000", 3, want);
    CHECK_STR(want, "1.00 " TIMES " 10\xE2\x81\xB7 pB");
    expected_rate("9995000", 4, want);
    CHECK_STR(want, "9.995 " TIMES " 10\xE2\x81\xB6 pB");
    expected_rate("4504500", 4, want);
    CHECK_STR(want, "4.504 " TIMES " 10\xE2\x81\xB6 pB");
    expected_rate("4505500", 4, want);
    CHECK_STR(want, "4.506 " TIMES " 10\xE2\x81\xB6 pB");
    /* No rate of the ladder begins with 95 or more, so none rounds up into the
     * next decade at any precision (test_limbs_round holds that branch). If the
     * hierarchy ever changes this, the count below says so. */
    for (level = 20; level < FRC_LEVEL_COUNT; level++) {
        for (digits = 2; digits <= 9; digits++) {
            const char *exact = oracle_pure_rate[level].num;
            char mantissa[24];
            if (round_decimal(exact, digits, mantissa) != (int)strlen(exact) - 1) {
                carried++;
            }
        }
    }
    CHECK_EQ_I64(carried, 0);

    TEST_SECTION("frc_format_level_rate: refused arguments");
    for (level = 0; level <= 255; level++) {
        for (digits = 0; digits <= 255; digits++) {
            int bad = level >= FRC_LEVEL_COUNT || digits == 1 || digits > 9;
            rate_level = (uint8_t)level;
            rate_digits = (uint8_t)digits;
            if (bad) {
                if (digits <= 12 || digits >= 250 || level % 16 == 0) {
                    CHECK_REFUSED(RATE_CALL, FRC_ERR_ARG);
                } else {
                    CHECK_EQ_I64(frc_format_level_rate((uint8_t)level, (uint8_t)digits, text, sizeof text), FRC_ERR_ARG);
                    CHECK_STR(text, "");
                }
            } else {
                CHECK(frc_format_level_rate((uint8_t)level, (uint8_t)digits, text, sizeof text) > 0);
            }
        }
    }

    TEST_SECTION("frc_format_level_rate: the buffer");
    {
        static const uint8_t cases[][2] = {{12, 0}, {10, 0}, {6, 0}, {0, 4}, {13, 0}, {16, 4},  {19, 9},
                                           {20, 0}, {20, 2}, {20, 9}, {29, 4}, {36, 3}, {62, 0}, {62, 9}};
        for (i = 0; i < sizeof cases / sizeof cases[0]; i++) {
            rate_level = cases[i][0];
            rate_digits = cases[i][1];
            CHECK(frc_format_level_rate(rate_level, rate_digits, want, sizeof want) > 0);
            CHECK_EVERY_SIZE(RATE_CALL, want);
        }
    }
    /* by hand: "2 772 pB" is 10 bytes */
    memset(text, '#', sizeof text);
    CHECK_EQ_I64(frc_format_level_rate(16, 0, text, 11), 10);
    CHECK_STR(text, "2" NNBSP "772 pB");
    CHECK_EQ_I64(frc_format_level_rate(16, 0, text, 10), FRC_ERR_BUFFER);
    CHECK_STR(text, "2" NNBSP "772 p");
    CHECK_EQ_I64(frc_format_level_rate(16, 0, text, 3), FRC_ERR_BUFFER);
    CHECK_STR(text, "2");
    CHECK_EQ_I64(frc_format_level_rate(16, 0, text, 1), FRC_ERR_BUFFER);
    CHECK_STR(text, "");
    CHECK_EQ_I64(frc_format_level_rate(16, 0, text, 0), FRC_ERR_BUFFER);
    CHECK_EQ_I64(frc_format_level_rate(16, 0, NULL, 11), FRC_ERR_BUFFER);
    /* "1.420 × 10¹⁴ pB": cut inside the sign and inside the exponent, it ends on a whole character */
    CHECK_EQ_I64(frc_format_level_rate(29, 4, text, 8), FRC_ERR_BUFFER);
    CHECK_STR(text, "1.420 ");
    CHECK_EQ_I64(frc_format_level_rate(29, 4, text, 14), FRC_ERR_BUFFER);
    CHECK_STR(text, "1.420 " TIMES " 10\xC2\xB9");
}

/* ------------------------------------------------------------------------- */
/* frc_i_limbs_round: the rounding behind the power-of-ten rates              */
/* ------------------------------------------------------------------------- */

/* Round `exact` (a decimal string, no leading zero) to every precision and
 * hold frc_i_limbs_round against round_decimal. */
static void check_limbs_round(const char *exact)
{
    uint32_t limbs[FRC_I_PREFIX_LIMBS];
    uint8_t used = limbs_of(exact, limbs);
    unsigned digits;

    for (digits = 1; digits <= 18; digits++) {
        char want[24], got[24];
        int32_t exponent = -1000;
        int want_exponent = round_decimal(exact, digits, want);
        uint64_t r = frc_i_limbs_round(limbs, used, (uint8_t)digits, &exponent);
        snprintf(got, sizeof got, "%" PRIu64, r);
        CHECK_STR(got, want);
        CHECK_NOTE("%s at %u digits", exact, digits);
        CHECK_EQ_I64(exponent, want_exponent);
        CHECK_NOTE("%s at %u digits", exact, digits);
    }
}

static void test_limbs_round(void)
{
    static const char *const numbers[] = {
        /* one digit, one limb, the ends of a limb */
        "1", "5", "7", "9", "10", "15", "25", "35", "95", "99", "100", "999999999", "1000000000", "1000000001",
        /* round up into the next decade: 9.996 -> 10.00 */
        "9996000", "9995000", "9994999", "99950", "99949", "999999999999999999", "9999999999999999995",
        "99999999999999999999999", "999999999999999999999999999999999999999999999999999999",
        /* ties: the digit after the last kept one is 5 and nothing follows */
        "4504500", "4505500", "125", "135", "1250000000", "1350000000", "12500000000000000000000",
        "13500000000000000000000", "250000000000000000000000000000000000000000000000000000",
        /* a 5 with something after it, however far, is not a tie */
        "1250000001", "12500000000000000000001", "250000000000000000000000000000000000000000000000000001",
        "4504500000000000000000000000000000000000000001",
        /* zeros across limb boundaries; a top limb of one digit and of nine */
        "1000000000000000000", "1000000005000000000", "5000000000000000000000000000", "500000000500000000",
        "100000000000000000000000000000000000000000000000000000", "123456789012345678901234567890123456789012345678901234",
        /* the last rung's rate and the largest prefix */
        "643235896490440623775983703125000000000000000", "18833464622317733633692970839722656250000000000000000"};
    size_t i;
    int k;

    TEST_SECTION("frc_i_limbs_round: chosen numbers at 1..18 digits");
    for (i = 0; i < sizeof numbers / sizeof numbers[0]; i++) {
        check_limbs_round(numbers[i]);
    }
    {
        uint32_t limbs[FRC_I_PREFIX_LIMBS];
        int32_t exponent = 0;
        /* typed in: 9 996 000 at three digits is 1.00 x 10^7; 4 504 500 at four is 4.504 x 10^6 */
        CHECK_EQ_U64(frc_i_limbs_round(limbs, limbs_of("9996000", limbs), 3, &exponent), 100);
        CHECK_EQ_I64(exponent, 7);
        CHECK_EQ_U64(frc_i_limbs_round(limbs, limbs_of("4504500", limbs), 4, &exponent), 4504);
        CHECK_EQ_I64(exponent, 6);
        CHECK_EQ_U64(frc_i_limbs_round(limbs, limbs_of("7", limbs), 3, &exponent), 700);
        CHECK_EQ_I64(exponent, 0);
    }

    TEST_SECTION("frc_i_limbs_round: random numbers of 1..54 digits");
    for (k = 0; k < 4000; k++) {
        char digits[64];
        size_t length = 1 + (size_t)(rng() % 54), j;
        unsigned kind = (unsigned)(rng() % 4);
        for (j = 0; j < length; j++) {
            /* plain random digits, or mostly 9 / 0 / 5 so that carries and ties are common */
            uint64_t roll = rng();
            char d = (char)('0' + roll % 10);
            if (kind == 1 && (roll >> 8) % 8 != 0) { d = '9'; }
            if (kind == 2 && (roll >> 8) % 8 != 0) { d = '0'; }
            if (kind == 3 && (roll >> 8) % 4 == 0) { d = '5'; }
            digits[j] = d;
        }
        if (digits[0] == '0') {
            digits[0] = (char)('1' + rng() % 9);
        }
        digits[length] = '\0';
        check_limbs_round(digits);
    }
}

